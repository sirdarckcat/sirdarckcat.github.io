#!/usr/bin/env python3
"""Generates fmw_step_L<L>.h: one Montgomery squaring step (times 2^b) on G groups of 8 lanes, L limbs of 52 bits (IFMA).

    python3 gen_fmw.py L [G] [variant]

The fm13 step (../fermat661/gen_fm13.py) for any L: a (limbs < 2^52, value A < 4n) -> Y = 2^b A^2 R^-1 mod n-ish (Y < 4n),
R = 2^(52 L), n < 2^(52 L - 12).
Phase 1: the square, off-diagonal products a_i a_j (i < j) once, doubled, plus the diagonal (column sums).
Phase 2: Montgomery reduction, L rounds of m = lo52(t_i ninv); t += m n 2^(52 i); carry t_i >> 52 into t_{i+1}.
Then b (a per-lane mask) doubles the high half, and a carry chain brings the limbs below 2^52.
Column sums stay below 106 * 2^52 < 2^59 for L <= 26 (phase 1: <= 54 * 2^52, phase 2 adds <= 2 L * 2^52), doubled < 2^60.

variant "win" (default): phase 1 stores the 2L columns to a stack array; phase 2 keeps a window of L + 1 columns in
variables (t_i .. t_{i+L}) and loads t_{i+L+1} as t_i retires, so at most ~L + 4 vectors are live (32 zmm registers).
variant "flat": the fm13 code shape (all 2L columns as variables; the compiler spills).
"""
import sys

L = int(sys.argv[1])
G = int(sys.argv[2]) if len(sys.argv) > 2 else 1
VAR = sys.argv[3] if len(sys.argv) > 3 else "win"
out = []
w = out.append
w("/* generated by gen_fmw.py %d %d %s -- do not edit */" % (L, G, VAR))
w("#define FMW_GROUPS %d" % G)
w("#define FMW_STEP(A, N, NINV, KB) do { \\")
for g in range(G):
    w("  { __m512i *a_ = (A) + %d * %d; const __m512i *n_ = (N) + %d * %d; const __m512i ninv_ = (NINV)[%d]; const __mmask8 kb_ = (KB)[%d]; \\" % (g, L, g, L, g, g))
    w("    const __m512i zero_ = _mm512_setzero_si512(); \\")
    if VAR in ("win", "win2", "win3"):
        w("    __m512i T_[%d]; \\" % (2 * L))
    for i in range(L):
        w("    const __m512i a%d = a_[%d]; \\" % (i, i))
    # phase 1: column k = 0 .. 2L-1: e_k = sum lo(a_i a_j), i<j, i+j=k  +  sum hi(a_i a_j), i<j, i+j=k-1 ; t_k = 2 e_k + diag
    if VAR in ("win2", "win3"):
        # columns in blocks of CB, each column with two accumulators (lo terms, hi terms), terms emitted round-robin over
        # the 2 CB chains so that independent IFMAs are adjacent in program order (chains of ~L/2 instead of ~L)
        CB = 4
        for k0 in range(0, 2 * L, CB):
            ks = [k for k in range(k0, min(k0 + CB, 2 * L))]
            chains = []
            for k in ks:
                lo = [("lo", i, k - i) for i in range(L) if i < k - i < L]
                hi = [("hi", i, k - 1 - i) for i in range(L) if i < k - 1 - i < L]
                chains.append(("l%d" % k, lo))
                chains.append(("h%d" % k, hi))
            started = set()
            depth = max(len(c[1]) for c in chains)
            for d in range(depth):
                for name, terms in chains:
                    if d < len(terms):
                        h, i, j = terms[d]
                        if name in started:
                            w("    %s = _mm512_madd52%s_epu64(%s, a%d, a%d); \\" % (name, h, name, i, j))
                        else:
                            started.add(name)
                            w("    __m512i %s = _mm512_madd52%s_epu64(zero_, a%d, a%d); \\" % (name, h, i, j))
            for k in ks:
                parts = [n for n in ("l%d" % k, "h%d" % k) if n in started]
                v = "e%d" % k
                if len(parts) == 2:
                    w("    __m512i %s = _mm512_add_epi64(%s, %s); %s = _mm512_add_epi64(%s, %s); \\" % (v, parts[0], parts[1], v, v, v))
                elif len(parts) == 1:
                    w("    __m512i %s = _mm512_add_epi64(%s, %s); \\" % (v, parts[0], parts[0]))
                else:
                    w("    __m512i %s = zero_; \\" % v)
                if k % 2 == 0:
                    w("    %s = _mm512_madd52lo_epu64(%s, a%d, a%d); \\" % (v, v, k // 2, k // 2))
                else:
                    w("    %s = _mm512_madd52hi_epu64(%s, a%d, a%d); \\" % (v, v, (k - 1) // 2, (k - 1) // 2))
                w("    T_[%d] = %s; \\" % (k, v))
    for k in (range(2 * L) if VAR not in ("win2", "win3") else []):
        terms = []
        for i in range(L):
            j = k - i
            if i < j < L:
                terms.append(("lo", i, j))
        for i in range(L):
            j = k - 1 - i
            if i < j < L:
                terms.append(("hi", i, j))
        v = "e%d" % k
        if terms:
            for n_, (h, i, j) in enumerate(terms):
                src = "zero_" if n_ == 0 else v
                decl = "__m512i " if n_ == 0 else ""
                w("    %s%s = _mm512_madd52%s_epu64(%s, a%d, a%d); \\" % (decl, v, h, src, i, j))
            w("    %s = _mm512_add_epi64(%s, %s); \\" % (v, v, v))
        else:
            w("    __m512i %s = zero_; \\" % v)
        if k % 2 == 0:
            w("    %s = _mm512_madd52lo_epu64(%s, a%d, a%d); \\" % (v, v, k // 2, k // 2))
        else:
            w("    %s = _mm512_madd52hi_epu64(%s, a%d, a%d); \\" % (v, v, (k - 1) // 2, (k - 1) // 2))
        if VAR == "win":
            w("    T_[%d] = %s; \\" % (k, v))
    # phase 2: reduction
    if VAR in ("win", "win2", "win3"):
        # window variables: t-index -> variable name; round i uses t_i .. t_{i+L}
        live = {}
        def var(c):
            return live[c]
        for c in range(L + 1):
            live[c] = "t%d" % c
            w("    __m512i t%d = T_[%d]; \\" % (c, c))
        for i in range(L):
            w("    { const __m512i m_ = _mm512_madd52lo_epu64(zero_, %s, ninv_); \\" % var(i))
            if VAR == "win3":
                # the next round's multiplier needs t_{i+1} = t_{i+1} + lo(m n_1) + hi(m n_0) + (t_i + lo(m n_0)) >> 52:
                # emit those first, the two products into separate registers so they run in parallel, then the rest
                w("      %s = _mm512_madd52lo_epu64(%s, m_, n_[0]); \\" % (var(i), var(i)))
                w("      const __m512i x_ = _mm512_madd52hi_epu64(zero_, m_, n_[0]); \\")
                w("      %s = _mm512_madd52lo_epu64(%s, m_, n_[1]); \\" % (var(i + 1), var(i + 1)))
                w("      %s = _mm512_add_epi64(%s, _mm512_add_epi64(x_, _mm512_srli_epi64(%s, 52))); \\" % (var(i + 1), var(i + 1), var(i)))
                for j in range(2, L):
                    w("      %s = _mm512_madd52lo_epu64(%s, m_, n_[%d]); \\" % (var(i + j), var(i + j), j))
                for j in range(1, L):
                    w("      %s = _mm512_madd52hi_epu64(%s, m_, n_[%d]); \\" % (var(i + j + 1), var(i + j + 1), j))
                w("    } \\")
            else:
                for j in range(L):
                    w("      %s = _mm512_madd52lo_epu64(%s, m_, n_[%d]); \\" % (var(i + j), var(i + j), j))
                for j in range(L):
                    w("      %s = _mm512_madd52hi_epu64(%s, m_, n_[%d]); \\" % (var(i + j + 1), var(i + j + 1), j))
                w("      %s = _mm512_add_epi64(%s, _mm512_srli_epi64(%s, 52)); } \\" % (var(i + 1), var(i + 1), var(i)))
            # retire t_i, its variable takes column i + L + 1
            nv = live.pop(i)
            if i + L + 1 < 2 * L:
                live[i + L + 1] = nv
                w("    %s = T_[%d]; \\" % (nv, i + L + 1))
        res = [var(k) for k in range(L, 2 * L)]
    else:
        for k in range(2 * L):
            w("    __m512i t%d = e%d; \\" % (k, k))
        for i in range(L):
            w("    { const __m512i m_ = _mm512_madd52lo_epu64(zero_, t%d, ninv_); \\" % i)
            for j in range(L):
                w("      t%d = _mm512_madd52lo_epu64(t%d, m_, n_[%d]); \\" % (i + j, i + j, j))
            for j in range(L):
                w("      t%d = _mm512_madd52hi_epu64(t%d, m_, n_[%d]); \\" % (i + j + 1, i + j + 1, j))
            w("      t%d = _mm512_add_epi64(t%d, _mm512_srli_epi64(t%d, 52)); } \\" % (i + 1, i + 1, i))
        res = ["t%d" % k for k in range(L, 2 * L)]
    # times 2^b, carry chain
    for r in res:
        w("    %s = _mm512_mask_add_epi64(%s, kb_, %s, %s); \\" % (r, r, r, r))
    w("    { const __m512i mask_ = _mm512_set1_epi64(0xFFFFFFFFFFFFFULL); \\")
    w("      __m512i v_ = %s; a_[0] = _mm512_and_si512(v_, mask_); __m512i c_ = _mm512_srli_epi64(v_, 52); \\" % res[0])
    for k in range(1, L):
        w("      v_ = _mm512_add_epi64(%s, c_); a_[%d] = _mm512_and_si512(v_, mask_); c_ = _mm512_srli_epi64(v_, 52); \\" % (res[k], k))
    w("    } } \\")
w("  } while (0)")
fn = "fmw_step_L%d.h" % L
open(fn, "w").write("\n".join(out) + "\n")
print("%s: L=%d, %d groups, variant %s, %d lines" % (fn, L, G, VAR, len(out)))
