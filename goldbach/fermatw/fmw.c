/* fmw.c -- fm13.c (../fermat661) for L limbs of 52 bits (compile-time FMW_L): base-2 Fermat tests of odd numbers of up to
 * 52 L - 12 bits, 8 lanes at a time with AVX-512 IFMA.  L = 20 / 21 / 23 / 26 for 300 / 320 / 350 / 400 digits.
 *
 * A lane computes y = 2^(1-n) mod n by t = bits(max n of the batch) - 6 Montgomery squaring steps that keep the residue as
 * a power of two (see ../fscan/fm_common.h and FERMAT26_STEP.md there: the start value is 2^e, the exponent bits are the
 * bits of (-E) mod 2^t), so nothing is converted to or from Montgomery form.  n is a probable prime to base 2 iff y == 1.
 * The step itself is fmw_step_L<L>.h (generated by gen_fmw.py): square, reduce, times 2^b, carry chain.
 *
 *   python3 gen_fmw.py 26 && gcc -O3 -march=native -shared -fPIC -DFMW_L=26 -DFMW_HDR='"fmw_step_L26.h"' -o libfmw26.so fmw.c
 */
#include <immintrin.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>
#ifndef FMW_L
#error "define FMW_L (limbs of 52 bits)"
#endif
#ifndef FMW_HDR
#error "define FMW_HDR, e.g. -DFMW_HDR='\"fmw_step_L26.h\"'"
#endif
#include FMW_HDR

typedef uint64_t u64;
typedef unsigned __int128 u128;
#define LIMBS FMW_L
#define RB (52 * LIMBS)        /* R = 2^(52 L) */
#define NW ((RB + 63) / 64)    /* 64-bit words of a number */
#define MAXBITS (RB - 12)
#define M52 ((1ULL << 52) - 1)

/* ------------------------------------------------------------------ little bignums, NW words */
static int bl_bits(const u64 *x) {
    for (int i = NW - 1; i >= 0; i--) if (x[i]) return 64 * i + 64 - __builtin_clzll(x[i]);
    return 0;
}
static int bl_ge(const u64 *a, const u64 *b) {
    for (int i = NW - 1; i >= 0; i--) if (a[i] != b[i]) return a[i] > b[i];
    return 1;
}
static void bl_sub(u64 *r, const u64 *a, const u64 *b) {          /* r = a - b (a >= b) */
    u64 br = 0;
    for (int i = 0; i < NW; i++) {
        u128 d = (u128)a[i] - b[i] - br;
        r[i] = (u64)d; br = (u64)(d >> 64) & 1;
    }
}
static void bl_add_small(u64 *r, const u64 *a, u64 s) {
    u64 c = s;
    for (int i = 0; i < NW; i++) { u128 v = (u128)a[i] + c; r[i] = (u64)v; c = (u64)(v >> 64); }
}
static void bl_shl(u64 *r, const u64 *a, int s) {                  /* r = a << s, s < 64 * NW (r != a) */
    int w = s >> 6, b = s & 63;
    for (int i = NW - 1; i >= 0; i--) {
        u64 v = 0;
        if (i - w >= 0) { v = a[i - w] << b; if (b && i - w - 1 >= 0) v |= a[i - w - 1] >> (64 - b); }
        r[i] = v;
    }
}
static void bl_dbl_mod(u64 *y, const u64 *n) {                      /* y = 2 y mod n, y < n < 2^(64 NW - 1) */
    u64 c = 0;
    for (int i = 0; i < NW; i++) { u64 v = y[i]; y[i] = (v << 1) | c; c = v >> 63; }
    if (bl_ge(y, n)) bl_sub(y, y, n);
}
static void to52(const u64 *x, u64 *l) {                            /* NW words -> L limbs of 52 bits */
    for (int k = 0; k < LIMBS; k++) {
        int bit = 52 * k, w = bit >> 6, b = bit & 63;
        u64 v = x[w] >> b;
        if (b > 12 && w + 1 < NW) v |= x[w + 1] << (64 - b);
        l[k] = v & M52;
    }
}
static void from52(const u64 *l, u64 *x) {
    memset(x, 0, 8 * NW);
    for (int k = 0; k < LIMBS; k++) {
        int bit = 52 * k, w = bit >> 6, b = bit & 63;
        x[w] |= l[k] << b;
        if (b > 12 && w + 1 < NW) x[w + 1] |= l[k] >> (64 - b);
    }
}
static u64 inv_neg52(u64 lo) {                                     /* -lo^-1 mod 2^52, lo odd */
    u64 x = (3 * lo) ^ 2;
    for (int i = 0; i < 4; i++) x *= 2 - lo * x;
    return (0 - x) & M52;
}

/* ------------------------------------------------------------------ one batch of up to 8 * FMW_GROUPS lanes */
#define LANES (8 * FMW_GROUPS)

/* n: cnt numbers of NW words.  yout (may be NULL): the final residue y < 4n of every lane as NW words, unreduced.
   verdict (may be NULL): 1 iff 2^(n-1) == 1 mod n.  cnt <= LANES. */
static void fmw_batch(int cnt, const u64 *n, uint8_t *verdict, u64 *yout) {
    _Alignas(64) __m512i A[FMW_GROUPS * LIMBS], N[FMW_GROUPS * LIMBS], NINV[FMW_GROUPS];
    _Alignas(64) u64 lane_a[LIMBS][8 * FMW_GROUPS], lane_n[LIMBS][8 * FMW_GROUPS], lane_ninv[8 * FMW_GROUPS];
    _Alignas(64) u64 ew[NW][8 * FMW_GROUPS];
    u64 nn[LANES][NW];
    int maxbits = 0;
    for (int i = 0; i < LANES; i++) {
        memcpy(nn[i], n + (size_t)(i < cnt ? i : 0) * NW, 8 * NW);        /* idle lanes repeat lane 0 */
        int b = bl_bits(nn[i]);
        if (b > maxbits) maxbits = b;
    }
    const int t = maxbits - 6;                                           /* steps */
    for (int i = 0; i < LANES; i++) {
        const u64 *ni = nn[i];
        int bn = bl_bits(ni);
        u64 E[NW], Cs[NW], Bt[NW], y[NW];
        bl_add_small(E, ni, RB - 1);                                     /* E = n + Rb - 1 */
        /* c = ceil(E / 2^t) */
        u64 c = 0;
        {
            int w = t >> 6, b = t & 63;
            u64 lo = w < NW ? E[w] >> b : 0;
            u64 hi = (w + 1 < NW && b) ? E[w + 1] << (64 - b) : 0;
            c = lo | hi;                                                 /* E >> t (small) */
            int rem = 0;
            for (int j = 0; j < w; j++) rem |= E[j] != 0;
            if (b && (E[w] & ((1ULL << b) - 1))) rem = 1;
            c += rem;
        }
        u64 cw[NW] = {0}; cw[0] = c;
        bl_shl(Cs, cw, t);                                               /* c 2^t */
        bl_sub(Bt, Cs, E);                                               /* B_t = c 2^t - E, 0 <= B_t < 2^t */
        bl_shl(E, Bt, 64 * NW - t);                                      /* top-aligned exponent bits (E reused) */
        for (int w = 0; w < NW; w++) ew[w][i] = E[w];
        /* start value y = 2^e, e = Rb - c, reduced when e > bits(n) */
        int e = RB - (int)c;
        memset(y, 0, sizeof y);
        if (e <= bn) y[e >> 6] = 1ULL << (e & 63);
        else {
            y[(bn - 1) >> 6] = 1ULL << ((bn - 1) & 63);
            for (int k = bn - 1; k < e; k++) bl_dbl_mod(y, ni);
        }
        u64 l52[LIMBS];
        to52(y, l52);
        for (int k = 0; k < LIMBS; k++) lane_a[k][i] = l52[k];
        to52(ni, l52);
        for (int k = 0; k < LIMBS; k++) lane_n[k][i] = l52[k];
        lane_ninv[i] = inv_neg52(ni[0]);
    }
    for (int g = 0; g < FMW_GROUPS; g++) {
        for (int k = 0; k < LIMBS; k++) {
            A[g * LIMBS + k] = _mm512_load_si512((const void *)&lane_a[k][8 * g]);
            N[g * LIMBS + k] = _mm512_load_si512((const void *)&lane_n[k][8 * g]);
        }
        NINV[g] = _mm512_load_si512((const void *)&lane_ninv[8 * g]);
    }
    __m512i EW[FMW_GROUPS] = {0};
    __mmask8 KB[FMW_GROUPS];
    for (int s = 0; s < t; s++) {
        if ((s & 63) == 0)
            for (int g = 0; g < FMW_GROUPS; g++) EW[g] = _mm512_load_si512((const void *)&ew[NW - 1 - (s >> 6)][8 * g]);   /* most significant word first */
        for (int g = 0; g < FMW_GROUPS; g++) { KB[g] = _mm512_movepi64_mask(EW[g]); EW[g] = _mm512_add_epi64(EW[g], EW[g]); }
        FMW_STEP(A, N, NINV, KB);
    }
    for (int g = 0; g < FMW_GROUPS; g++)
        for (int k = 0; k < LIMBS; k++) _mm512_store_si512((void *)&lane_a[k][8 * g], A[g * LIMBS + k]);
    for (int i = 0; i < cnt; i++) {
        u64 l52[LIMBS], y[NW];
        for (int k = 0; k < LIMBS; k++) l52[k] = lane_a[k][i];
        from52(l52, y);
        if (yout) memcpy(yout + (size_t)i * NW, y, 8 * NW);
        if (verdict) {
            const u64 *ni = nn[i];
            while (bl_ge(y, ni)) bl_sub(y, y, ni);
            int one = y[0] == 1;
            for (int w = 1; w < NW; w++) one &= y[w] == 0;
            verdict[i] = (uint8_t)one;
        }
    }
}

/* cnt numbers of NW words each (little endian); any cnt.  Numbers of one call batch together in order, so put numbers of
   equal bit length next to each other. */
void fmw_test(int cnt, const u64 *n, uint8_t *verdict, u64 *yout) {
    for (int i = 0; i < cnt; i += LANES) {
        int m = cnt - i < LANES ? cnt - i : LANES;
        fmw_batch(m, n + (size_t)i * NW, verdict ? verdict + i : NULL, yout ? yout + (size_t)i * NW : NULL);
    }
}
int fmw_lanes(void) { return LANES; }
int fmw_limbs(void) { return LIMBS; }
int fmw_words(void) { return NW; }
int fmw_maxbits(void) { return MAXBITS; }

/* ------------------------------------------------------------------ members: the Fermat loop of search.run_block */
static void bl_mul_small_add(u64 *r, const u64 *a, u64 k, const u64 *b) {     /* r = a * k + b (fits NW words) */
    u128 c = 0;
    for (int i = 0; i < NW; i++) {
        c += (u128)a[i] * k + b[i];
        r[i] = (u64)c;
        c >>= 64;
    }
}
static void bl_sub_small(u64 *r, const u64 *a, u64 q) {
    u64 br = q;
    for (int i = 0; i < NW; i++) {
        u128 d = (u128)a[i] - br;
        r[i] = (u64)d;
        br = (u64)(d >> 64) & 1;
    }
}

typedef struct { int m; int pos; u64 base[NW]; } slot_t;

/* Member i (0 <= i < nm) has the number n = N0 + kv[i] * M - U[rows[j]] for every j in offs[i] .. offs[i+1]-1, to be tried in
   that order until the first probable prime (as search.run_block does).  first_pos[i] = the position within its list of the
   first number that passes, or -1.  The lanes of a batch hold the next number of 8 * FMW_GROUPS different members.
   Returns the number of batches run.  N0 and M have NW words. */
int64_t fmw_members(const u64 *N0, const u64 *M, const uint32_t *U, int nm, const u64 *kv, const uint16_t *rows,
                     const int64_t *offs, int32_t *first_pos) {
    slot_t slot[LANES];
    int lane_slot[LANES];
    u64 nbuf[LANES][NW];
    uint8_t vd[LANES];
    int next = 0;
    int64_t batches = 0;
    for (int i = 0; i < LANES; i++) slot[i].m = -1;
    for (;;) {
        for (int i = 0; i < LANES; i++) {
            if (slot[i].m >= 0) continue;
            while (next < nm && offs[next + 1] == offs[next]) first_pos[next++] = -1;
            if (next >= nm) continue;
            slot[i].m = next;
            slot[i].pos = 0;
            bl_mul_small_add(slot[i].base, M, kv[next], N0);
            next++;
        }
        int cnt = 0;
        for (int i = 0; i < LANES; i++) {
            if (slot[i].m < 0) continue;
            bl_sub_small(nbuf[cnt], slot[i].base, U[rows[offs[slot[i].m] + slot[i].pos]]);
            lane_slot[cnt++] = i;
        }
        if (!cnt) break;
        fmw_batch(cnt, &nbuf[0][0], vd, NULL);
        batches++;
        for (int c = 0; c < cnt; c++) {
            slot_t *s = &slot[lane_slot[c]];
            if (vd[c]) { first_pos[s->m] = s->pos; s->m = -1; }
            else if (offs[s->m] + ++s->pos == offs[s->m + 1]) { first_pos[s->m] = -1; s->m = -1; }
        }
    }
    return batches;
}
