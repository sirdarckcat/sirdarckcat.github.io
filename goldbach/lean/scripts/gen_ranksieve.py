#!/usr/bin/env python3
"""Generate GoldbachGaps/RankSieve.lean: the least Goldbach summand of every even N below 2^25,
settled in the kernel by the bitmask sieve of GoldbachGaps/BitSieve.lean.

    python3 -I scripts/gen_ranksieve.py scripts/rank_sieve/scan_2e25.txt GoldbachGaps/RankSieve.lean

scan file (from scripts/rank_sieve/classmax.c and topten.c): lines "record N g" (the record
holders below X), "class m G N" (the largest least summand G among the multiples of m, attained
at N) and "piece m A B c M:g ..." (on [A, B) the multiples of m have least summand at most c, and
the ten numbers M below A have least summand g >= c).  None of it is trusted: every statement is
checked again by the kernel, and a wrong line makes the build fail.  The numbers M:g must have
certificates in GoldbachGaps/RankData.lean (group "witness" of scripts/rank_records/certified.txt;
this script prints the line to put there).

Layout: [6, 4096) by trial division; [4096, 2^14) sieved by the primes below 128; [2^14, 2^20)
by the primes below 1024; then 31 segments of length 2^20 sieved by the primes below 5800.
Each sieve segment starts 1000 below its interval, so that N - q is in it for every q < 1000.
"""
import sys

X = 2 ** 25
TINY = 4096
BACK = 1000          # the q used are below this
DMAX = 5800          # sieving primes are below this; DMAX^2 >= X


def primes_below(n):
    s = bytearray([1]) * n
    s[0:2] = b"\x00\x00"
    for i in range(2, int(n ** 0.5) + 1):
        if s[i]:
            s[i * i::i] = bytearray(len(s[i * i::i]))
    return [i for i in range(n) if s[i]]


def lean_list(xs, indent="  ", width=98):
    lines, cur = [], indent + "["
    for i, x in enumerate(xs):
        tok = str(x) + ("," if i + 1 < len(xs) else "]")
        if len(cur) + len(tok) + 1 > width and cur.strip() != "[":
            lines.append(cur.rstrip())
            cur = indent + " " + tok
        else:
            cur += ("" if cur.endswith("[") else " ") + tok
    lines.append(cur)
    return "\n".join(lines)


def tup(s):
    return "(%d, %d, %d, %d)" % s


def main():
    scan, out = sys.argv[1], sys.argv[2]
    records, classes, pieces = [], [], {}
    for line in open(scan):
        f = line.split()
        if not f or f[0].startswith("#"):
            continue
        if f[0] == "record":
            records.append((int(f[1]), int(f[2])))
        elif f[0] == "class":
            classes.append((int(f[1]), int(f[2]), int(f[3])))
        elif f[0] == "piece":
            pieces.setdefault(int(f[1]), []).append(
                (int(f[2]), int(f[3]), int(f[4]), [tuple(map(int, t.split(":"))) for t in f[5:]]))
    assert records[0] == (6, 3) and all(a[0] < b[0] and a[1] < b[1] for a, b in zip(records, records[1:]))
    assert records[-1][0] < X and records[-1][1] < BACK and all(G < BACK for _, G, _ in classes)
    assert DMAX * DMAX >= X and DMAX <= 5929

    # intervals: (A, B, D); D = 0 for the trial-division range
    intervals = [(6, TINY, 0), (TINY, 2 ** 14, 128), (2 ** 14, 2 ** 20, 1024)]
    intervals += [(k * 2 ** 20, (k + 1) * 2 ** 20, DMAX) for k in range(1, X // 2 ** 20)]
    assert intervals[-1][1] == X

    # running-record pieces: [N_j, N_{j+1}) with bound g_j, cut at the interval boundaries
    rec_bounds = [n for n, _ in records] + [X]
    def rec_pieces(A, B):
        res = []
        for j, (n, g) in enumerate(records):
            lo, hi = max(A, n), min(B, rec_bounds[j + 1])
            if lo < hi:
                res.append((lo, hi, 2, g))
        return res

    # "never among the ten largest" pieces, cut at the interval boundaries
    def top_pieces(A, B):
        res = []
        for m, pl in pieces.items():
            for pA, pB, c, wit in pl:
                assert len(wit) == 10 and all(M < pA and g >= c for M, g in wit)
                lo, hi = max(A, pA), min(B, pB)
                if lo < hi:
                    res.append((lo, hi, m, c))
        return res

    specs = []                      # one list per interval
    top_chain = {m: [] for m in pieces}
    for A, B, D in intervals:
        tp = top_pieces(A, B)
        for s in tp:
            top_chain[s[2]].append(s)
        sl = rec_pieces(A, B) + [(A, B, m, G) for m, G, _ in classes]
        specs.append(sl + [s for s in tp if s not in sl])
    rec_chain = [s for sl in specs for s in sl if s[2] == 2]
    class_chain = {m: [(A, B, m, G) for A, B, _ in intervals] for m, G, _ in classes}
    witnesses = sorted({w for pl in pieces.values() for _, _, _, wit in pl for w in wit})

    nrec = len(records)
    P = primes_below(DMAX)
    L = []
    w = L.append
    w("import GoldbachGaps.BitSieve")
    w("import GoldbachGaps.RankData")
    w("")
    w("/-!")
    w("# The least Goldbach summand of every even number below `2^25`")
    w("")
    w("Generated by `scripts/gen_ranksieve.py` from `scripts/rank_sieve/scan_2e25.txt`; do not edit by")
    w("hand. The scan is not trusted: each `seg*_check` below is a sieve of one interval evaluated by")
    w("the kernel (`GoldbachGaps/BitSieve.lean`), and the final theorems follow from those checks.")
    w("")
    w("* `exists_summand_le` : every even `N` with `6 ≤ N < 2^25` is `q + p` with `q`, `p` prime and")
    w(f"  `q ≤ {records[-1][1]}` (Goldbach's conjecture below `2^25 = 33554432`, with the size of the least")
    w("  summand).")
    w(f"* `isRecordHolder_iff` : below `2^25` the record holders are exactly the {nrec} numbers of")
    w("  `records25` (the first entries of `RankData.recordTable`): a theorem, where")
    w("  `scripts/rank_records` had a scan.")
    for m, G, n in classes:
        w(f"* `exists_summand_le_of_dvd_{m}` : a multiple of `{m}` below `2^25` has a summand at most `{G}`")
        w(f"  (attained: `RankData.leastSummand_{n}`).")
    w("")
    for m, pl in pieces.items():
        w(f"* `notAmongTen_of_dvd_{m}` : no multiple of `{m}` between `{pl[0][0] - m}` and `2^25` enters the ten largest")
        w("  least summands: ten smaller even numbers always have one at least as large.")
    w("")
    w("So on this range the pattern of the rank experiment is a theorem: the numbers with a large")
    w("least summand are not divisible by a small odd prime. For the multiples of `3` the largest")
    w(f"value is `{dict((m, G) for m, G, _ in classes)[6]}`, against `{records[-1][1]}` for all even numbers, and after `1362`")
    w("none of them is ever among the ten largest.")
    w("-/")
    w("")
    w("-- One sieve at a time: each `seg*_check` holds about a gigabyte of intermediate numbers while")
    w("-- the kernel evaluates it, and checking several in parallel would multiply that.")
    w("set_option Elab.async false")
    w("")
    w("namespace GoldbachGaps.RankSieve")
    w("")
    w("open BitSieve")
    w("")
    w(f"/-- The primes below `{DMAX}`. -/")
    w(f"def primes{DMAX} : List ℕ :=")
    w(lean_list(P))
    w("")
    w("set_option maxRecDepth 1000000 in")
    w(f"theorem primes{DMAX}_eq : sievePrimesBelow {DMAX} = primes{DMAX} := by decide +kernel")
    w("")
    w(f"theorem mem_primes{DMAX} {{p : ℕ}} : p ∈ primes{DMAX} ↔ p.Prime ∧ p < {DMAX} := by")
    w(f"  rw [← primes{DMAX}_eq]")
    w("  exact mem_sievePrimesBelow (by norm_num)")
    w("")
    w(f"theorem mem_ds {{D : ℕ}} (hD : D ≤ {DMAX}) :")
    w(f"    ∀ p, p.Prime → p < D → p ∈ primes{DMAX}.filter (· < D) := by")
    w("  intro p hp hlt")
    w("  rw [List.mem_filter, decide_eq_true_eq]")
    w(f"  exact ⟨mem_primes{DMAX}.mpr ⟨hp, by omega⟩, hlt⟩")
    w("")
    w(f"theorem prime_of_mem_qs : ∀ q ∈ primes{DMAX}.filter (· < {BACK}), q.Prime := fun _ hq =>")
    w(f"  (mem_primes{DMAX}.mp (List.mem_of_mem_filter hq)).1")
    w("")
    names = []
    for k, ((A, B, D), sl) in enumerate(zip(intervals, specs)):
        name = f"specs{k}"
        names.append(name)
        w(f"/-- The statements for the interval `[{A}, {B})`. -/")
        w(f"def {name} : List (ℕ × ℕ × ℕ × ℕ) :=")
        w("  [" + ",\n   ".join(tup(s) for s in sl) + "]")
        w("")
        w("set_option maxRecDepth 1000000 in")
        if D == 0:
            w(f"theorem seg{k}_check :")
            w(f"    {name}.all (tinyCheck (primes{DMAX}.filter (· < {BACK}))) = true := by")
            w("  decide +kernel")
            w("")
            w(f"theorem seg{k} : ∀ s ∈ {name}, Holds s := fun s hs =>")
            w(f"  holds_of_tinyCheck prime_of_mem_qs (List.all_eq_true.mp seg{k}_check s hs)")
        else:
            a = A - BACK
            w(f"theorem seg{k}_check :")
            w(f"    segCheck {a} {B - a} {D} (primes{DMAX}.filter (· < {D}))")
            w(f"      (primes{DMAX}.filter (· < {BACK})) {name} = true := by")
            w("  decide +kernel")
            w("")
            w(f"theorem seg{k} : ∀ s ∈ {name}, Holds s :=")
            w(f"  holds_of_segCheck (mem_ds (by norm_num)) prime_of_mem_qs seg{k}_check")
        w("")
    w("/-- All the statements proved above. -/")
    w("def allSpecs : List (ℕ × ℕ × ℕ × ℕ) :=")
    w("  List.flatten")
    w(lean_list(names, indent="    "))
    w("")
    w("theorem allSpecs_holds : ∀ s ∈ allSpecs, Holds s := by")
    w("  intro s hs")
    w("  obtain ⟨l, hl, hsl⟩ := List.mem_flatten.mp hs")
    w("  simp only [List.mem_cons, List.not_mem_nil, or_false] at hl")
    w("  rcases hl with " + " | ".join("rfl" for _ in names))
    for k in range(len(names)):
        w(f"  · exact seg{k} s hsl")
    w("")

    def chain(name, doc, ch):
        w(f"/-- {doc} -/")
        w(f"def {name} : List (ℕ × ℕ × ℕ × ℕ) :=")
        w("  [" + ",\n   ".join(tup(s) for s in ch) + "]")
        w("")
        w("set_option maxRecDepth 1000000 in")
        w(f"theorem {name}_holds : ∀ s ∈ {name}, Holds s := by")
        w(f"  have h : ∀ s ∈ {name}, s ∈ allSpecs := by decide +kernel")
        w("  exact fun s hs => allSpecs_holds s (h s hs)")
        w("")

    chain("recChain", "The running record: on `[A, B)` every even number has a summand at most the value of "
          "the last\nrecord holder at or before `A`.", rec_chain)
    w(f"/-- The record holders below `2^25` with their least summands. -/")
    w("def records25 : List (ℕ × ℕ) :=")
    w("  [" + ",\n   ".join("(%d, %d)" % r for r in records) + "]")
    w("")
    w("theorem records25_spec : ∀ x ∈ records25, IsLeastSummand x.1 x.2 := by")
    w("  have h : ∀ x ∈ records25, x ∈ RankData.recordTable := by decide")
    w("  exact fun x hx => RankData.recordTable_spec x (h x hx)")
    w("")
    w("set_option maxRecDepth 1000000 in")
    w("theorem recChain_isChain : isChain 6 (2 ^ 25) recChain = true := by decide +kernel")
    w("")
    w("set_option maxRecDepth 1000000 in")
    w("theorem recChain_link : recLinkOK recChain records25 = true := by decide +kernel")
    w("")
    w("set_option maxRecDepth 1000000 in")
    w("theorem recChain_table : recTableOK (2 ^ 25) recChain records25 = true := by decide +kernel")
    w("")
    w("set_option maxRecDepth 1000000 in")
    w(f"theorem recChain_shape : shapeOK 2 {records[-1][1]} recChain = true := by decide +kernel")
    w("")
    w(f"/-- **Goldbach below `2^25`, with the least summand.** Every even `N` with `6 ≤ N < 2^25` is")
    w(f"the sum of two primes, the smaller of which is at most `{records[-1][1]}`. -/")
    w("theorem exists_summand_le {N : ℕ} (hE : Even N) (h6 : 6 ≤ N) (hX : N < 2 ^ 25) :")
    w(f"    ∃ q, q ≤ {records[-1][1]} ∧ IsSummand N q :=")
    w("  summand_of_chain recChain_isChain recChain_holds recChain_shape h6 hX hE.two_dvd")
    w("")
    w(f"/-- **The record holders below `2^25` are exactly the {nrec} numbers of the table.** An even")
    w("`N` with `6 ≤ N < 2^25` has a least Goldbach summand larger than that of every smaller even")
    w("number from `6` on if and only if it is one of")
    w("`" + ", ".join(str(n) for n, _ in records) + "`. -/")
    w("theorem isRecordHolder_iff {N : ℕ} (hE : Even N) (h6 : 6 ≤ N) (hX : N < 2 ^ 25) :")
    w("    IsRecordHolder N ↔ N ∈ records25.map Prod.fst := by")
    w("  constructor")
    w("  · exact mem_of_isRecordHolder recChain_isChain recChain_holds recChain_link records25_spec")
    w("      recChain_table hE h6 hX")
    w("  · intro h")
    w("    obtain ⟨x, hx, rfl⟩ := List.mem_map.mp h")
    w("    exact isRecordHolder_of_mem recChain_isChain recChain_holds recChain_link records25_spec")
    w("      recChain_table x hx")
    w("")
    for m, G, n in classes:
        nm = f"chain{m}"
        chain(nm, f"The multiples of `{m}`: on each interval a summand at most `{G}`.", class_chain[m])
        w("set_option maxRecDepth 1000000 in")
        w(f"theorem {nm}_isChain : isChain 6 (2 ^ 25) {nm} = true := by decide +kernel")
        w("")
        w("set_option maxRecDepth 1000000 in")
        w(f"theorem {nm}_shape : shapeOK {m} {G} {nm} = true := by decide +kernel")
        w("")
        w(f"/-- **Multiples of `{m}` below `2^25`.** Each has a Goldbach summand at most `{G}`; the bound is")
        w(f"attained at `{n}` (`RankData.leastSummand_{n}`). -/")
        w(f"theorem exists_summand_le_of_dvd_{m} {{N : ℕ}} (hm : {m} ∣ N) (hpos : 0 < N) (hX : N < 2 ^ 25) :")
        w(f"    ∃ q, q ≤ {G} ∧ IsSummand N q :=")
        w(f"  summand_of_chain {nm}_isChain {nm}_holds {nm}_shape")
        w(f"    (le_trans (by norm_num) (Nat.le_of_dvd hpos hm)) hX hm")
        w("")
        w(f"/-- The bound `{G}` for the multiples of `{m}` is attained. -/")
        w(f"theorem isLeastSummand_{n} : IsLeastSummand {n} {G} := RankData.leastSummand_{n}")
        w("")
    for m, pl in pieces.items():
        nm = f"top{m}"
        lo = pl[0][0]
        G = max(c for _, _, c, _ in pl)
        chain(nm, f"The multiples of `{m}` from `{lo}` on: on each interval a summand at most the bound, and ten\n"
              f"numbers of `RankData.witnessTable` below the interval with least summand at least the bound.",
              top_chain[m])
        w("set_option maxRecDepth 1000000 in")
        w(f"theorem {nm}_isChain : isChain {lo} (2 ^ 25) {nm} = true := by decide +kernel")
        w("")
        w("set_option maxRecDepth 1000000 in")
        w(f"theorem {nm}_shape : shapeOK {m} {G} {nm} = true := by decide +kernel")
        w("")
        w("set_option maxRecDepth 1000000 in")
        w(f"theorem {nm}_ten : tenOK {nm} RankData.witnessTable = true := by decide +kernel")
        w("")
        w(f"/-- **No multiple of `{m}` between `{lo - m}` and `2^25` enters the ten largest.** For every `N`")
        w(f"divisible by `{m}` with `{lo - m} < N < 2^25`, ten smaller even numbers have a least Goldbach summand at")
        w(f"least as large as that of `N`. (`{lo - m}` itself does enter the ten largest, by the scan.) -/")
        w(f"theorem notAmongTen_of_dvd_{m} {{N : ℕ}} (hm : {m} ∣ N) (hlo : {lo - m} < N) (hX : N < 2 ^ 25) :")
        w("    NotAmongTen N := by")
        w(f"  have h1 : {lo} ≤ N := by")
        w("    obtain ⟨k, rfl⟩ := hm")
        w("    omega")
        w(f"  exact notAmongTen_of_chain {nm}_isChain {nm}_holds {nm}_shape RankData.witnessTable_spec")
        w(f"    {nm}_ten h1 hX hm")
        w("")
    w("end GoldbachGaps.RankSieve")
    w("")
    open(out, "w").write("\n".join(L))
    nseg = sum(1 for _, _, D in intervals if D)
    print(f"wrote {out}: {nseg} sieve segments, {sum(len(sl) for sl in specs)} statements, "
          f"{len(rec_chain)} record pieces, {len(classes)} classes")
    print("certificates needed in scripts/rank_records/certified.txt:")
    print("classmax " + " ".join(f"{n}:{G}" for _, G, n in classes))
    print("witness " + " ".join(f"{M}:{g}" for M, g in witnesses))


if __name__ == "__main__":
    main()
