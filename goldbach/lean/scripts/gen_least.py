#!/usr/bin/env python3
"""Generate Lean certificates `IsLeastSummand N g` for small N (the composite rows by exhibited
prime divisors, the two primes by Mathlib's `primality`), and tables of them.

    python3 -I scripts/gen_least.py groups.txt out.lean

groups.txt: one group per line, `name N:g N:g ...` (lines starting with # are ignored). Each
distinct N gets `mods<N>` and `leastSummand_<N>`; each group gets `<name>Table : List (ℕ × ℕ)` and
`<name>Table_spec : ∀ x ∈ <name>Table, IsLeastSummand x.1 x.2`.
"""
import sys


def primes_below(n):
    s = bytearray([1]) * max(n, 2)
    s[0:2] = b"\x00\x00"
    for i in range(2, int(n ** 0.5) + 1):
        if s[i]:
            s[i * i::i] = bytearray(len(s[i * i::i]))
    return [i for i in range(n) if s[i]]


SMALL = primes_below(400000)


def least_factor(m):
    for d in SMALL:
        if d * d > m:
            return m
        if m % d == 0:
            return d
    raise ValueError(m)


def lean_list(xs, indent="  ", width=96):
    if not xs:
        return indent + "[]"
    lines, cur = [], indent + "["
    for i, x in enumerate(xs):
        tok = str(x) + ("," if i + 1 < len(xs) else "]")
        if len(cur) + len(tok) + 1 > width and cur.strip() != "[":
            lines.append(cur.rstrip())
            cur = indent + " " + tok
        else:
            cur += ("" if cur.endswith("[") else " ") + tok
    lines.append(cur)
    return "\n".join(lines)


def main():
    groups = []
    for line in open(sys.argv[1]):
        if line.strip() and not line.startswith("#"):
            name, *items = line.split()
            groups.append((name, [tuple(map(int, t.split(":"))) for t in items]))
    pairs = sorted({p for _, items in groups for p in items})
    gmax = max(g for _, g in pairs)
    small = primes_below(int(gmax ** 0.5) + 2)
    L = ["import GoldbachGaps.Needles", "", "/-!", "# Least Goldbach summands: generated certificates", "",
         "Generated by `scripts/gen_least.py`; do not edit by hand. For each `N` below with value `g`:",
         "every `N - q`, `q < g` prime, is divisible by one of the listed primes (smaller than it), and `g`",
         "and `N - g` are prime. The data is not trusted: the kernel re-evaluates each block test and",
         "checks each primality proof.", "-/", "", "namespace GoldbachGaps.RankData", "",
         "/-- Trial divisors for the primes below the largest value. -/",
         "def smallPrimes : List ℕ :=", lean_list(small), ""]
    for N, g in pairs:
        rows = primes_below(g)
        mods = set()
        for q in rows:
            f = least_factor(N - q)
            assert f < N - q, f"{N} - {q} is prime"
            mods.add(f)
        mods = sorted(mods)
        assert least_factor(g) == g and least_factor(N - g) == N - g and g + 2 < N
        assert all(r + g < N for r in mods)
        L += [f"/-- Prime divisors of the numbers `{N} - q`, `q < {g}` prime. -/",
              f"def mods{N} : List ℕ :=", lean_list(mods), "",
              "set_option maxRecDepth 1000000 in",
              f"theorem leastSummand_{N} : IsLeastSummand {N} {g} := by",
              f"  have hl : desertListsCheck {N} {g} mods{N} smallPrimes = true := by decide +kernel",
              f"  have hb : desertBlockCheck {N} 0 {g} mods{N} smallPrimes [] = true := by",
              "    decide +kernel",
              "  have hn := (covered_of_desertBlockCheck_nil hl hb).noSummandIn hl (by norm_num)",
              f"  have hc : Nat.Prime ({N} - {g}) := by",
              f"    rw [show ({N} : ℕ) - {g} = {N - g} by norm_num]",
              "    primality",
              "  exact isLeastSummand_of_noSummandIn (fun q h0 hq => hn q h0 (by omega)) (by primality) hc",
              ""]
    for name, items in groups:
        L += [f"/-- The table `{name}`: pairs `(N, g(N))`. -/",
              f"def {name}Table : List (ℕ × ℕ) :=",
              "  [" + ",\n   ".join(f"({N}, {g})" for N, g in items) + "]", "",
              f"theorem {name}Table_spec : ∀ x ∈ {name}Table, IsLeastSummand x.1 x.2 := by",
              "  intro x hx",
              f"  simp only [{name}Table, List.mem_cons, List.not_mem_nil, or_false] at hx",
              "  rcases hx with " + " | ".join("rfl" for _ in items)]
        L += [f"  · exact leastSummand_{N}" for N, _ in items]
        L += [""]
    L += ["end GoldbachGaps.RankData", ""]
    open(sys.argv[2], "w").write("\n".join(L))
    print(f"wrote {sys.argv[2]}: {len(pairs)} certificates, {len(groups)} tables")


if __name__ == "__main__":
    main()
