#!/usr/bin/env python3
"""Generate GoldbachGaps/CoverDepthMore.lean: kernel-checked lower bounds for the cover depth from explicit vectors.

    python3 -I scripts/gen_coverdepth_more.py scripts/cover_depth/exact_depth_vectors.txt > GoldbachGaps/CoverDepthMore.lean

Each input line is "n D modulus:class ...": a class vector on the first n odd primes that covers every odd prime
below D.  The script checks that itself before writing the theorem; Lean checks it again in the kernel.
"""
import sys


def primes(n):
    s = bytearray([1]) * (n + 1); s[0] = s[1] = 0
    for i in range(2, int(n ** 0.5) + 1):
        if s[i]: s[i * i::i] = bytearray(len(s[i * i::i]))
    return [i for i in range(n + 1) if s[i]]


def main():
    odd = [p for p in primes(6000) if p > 2]
    rows = []
    for line in open(sys.argv[1]):
        if not line.strip() or line.startswith('#'): continue
        t = line.split(); n, D = int(t[0]), int(t[1]); vec = [tuple(map(int, u.split(':'))) for u in t[2:]]
        assert [r for r, _ in vec] == odd[:n], n
        assert D <= 5929 and all(any(q % r == a % r for r, a in vec) for q in odd if q < D), n
        rows.append((n, D, vec))
    out = []
    out.append("import GoldbachGaps.CoverDepth\n")
    out.append("/-!\n# More lower bounds for the cover depth\n")
    out.append("Generated by `scripts/gen_coverdepth_more.py` from `scripts/cover_depth/exact_depth_vectors.txt`: for")
    out.append("each `n` below, an explicit class vector on the first `n` odd primes that covers every odd prime below")
    out.append("the value `D(n)` found by the uarch session's exhaustive searches (branch `ccr-b8c25887-i6tn9f`). The")
    out.append("kernel checks the vector, so `D(n)` is proved as a **lower bound** for the depth: `CoversBelow mods D`.")
    out.append("That no vector goes further is that session's computation and is not checked here.\n")
    out.append("| n | " + " | ".join(str(n) for n, _, _ in rows) + " |")
    out.append("|---|" + "---|" * len(rows))
    out.append("| depth at least | " + " | ".join(str(D) for _, D, _ in rows) + " |")
    out.append("-/\n")
    out.append("namespace GoldbachGaps.CoverDepth\n")
    for n, D, vec in rows:
        mods = ", ".join(str(r) for r, _ in vec)
        pairs = ", ".join(f"({r}, {a})" for r, a in vec)
        doc = " ".join(f"{r}:{a}" for r, a in vec)
        out.append(f"/-- Some class vector on the first {n} odd primes covers every odd prime below `{D}`:")
        out.append(f"`{doc}`. -/")
        out.append(f"theorem coversBelow_{n} :")
        out.append(f"    CoversBelow\n      [{mods}] {D} :=")
        out.append("  coversBelow_of_check (by norm_num)")
        out.append(f"    (fun r => (([{pairs}] : List (ℕ × ℕ)).lookup r).getD 0)")
        out.append("    (by decide +kernel)\n")
    out.append("end GoldbachGaps.CoverDepth")
    print("\n".join(out))


if __name__ == "__main__":
    main()
