#!/usr/bin/env python3
"""Generate a Lean file certifying a COMPLETE cover: an even N such that for every prime q < Q
the number N - q is divisible by one of a short list of moduli. No primality or compositeness
test is involved; Lean's kernel re-evaluates one Boolean block test per BLOCK offsets
(`GoldbachGaps.desertBlockCheck` with an empty list of residuals).

    python3 -I scripts/gen_cover.py N Q MODULI Namespace out.lean ["label of the source"]

N       the even integer, in decimal
Q       the bound: all primes q < Q are covered
MODULI  the covering moduli, comma separated (2 is added: N - 2 is even)

The script checks the cover itself before writing anything and refuses an incomplete one.
"""
import sys

# Offsets per block theorem (one kernel evaluation each).
BLOCK = 8192


def primes_below(n):
    sieve = bytearray([1]) * max(n, 2)
    sieve[0:2] = b"\x00\x00"
    for i in range(2, int(n ** 0.5) + 1):
        if sieve[i]:
            sieve[i * i::i] = bytearray(len(sieve[i * i::i]))
    return [i for i in range(n) if sieve[i]]


def lean_list(xs, indent="  ", width=96):
    if not xs:
        return indent + "[]"
    lines, cur = [], indent + "["
    for i, x in enumerate(xs):
        tok = str(x) + ("," if i + 1 < len(xs) else "]")
        if len(cur) + len(tok) + 1 > width and cur.strip() != "[":
            lines.append(cur.rstrip())
            cur = indent + " " + tok
        else:
            cur += ("" if cur.endswith("[") else " ") + tok
    lines.append(cur)
    return "\n".join(lines)


def main():
    if len(sys.argv) < 6:
        sys.exit(__doc__)
    N = int(sys.argv[1])
    Q = int(sys.argv[2])
    mods = sorted(set([2] + [int(x) for x in sys.argv[3].split(",") if x.strip()]))
    namespace, out = sys.argv[4], sys.argv[5]
    label = sys.argv[6] if len(sys.argv) > 6 else "command line"

    assert N % 2 == 0, "N must be even"
    assert all(r >= 2 for r in mods)
    assert all(r + Q < N for r in mods) and Q + 2 < N, "N is too small for the moduli"
    rows = primes_below(Q)
    bad = [q for q in rows if not any((N - q) % r == 0 for r in mods)]
    assert not bad, "the cover is not complete: %d primes left, the first is %d" % (len(bad), bad[0])
    small_primes = primes_below(int(Q ** 0.5) + 2)
    # every composite q < Q must have a proper divisor among the trial divisors
    for q in range(2, Q):
        if q not in set(rows):
            assert any(d < q and q % d == 0 for d in small_primes)
    big = max(mods)
    digits = len(str(N))

    L = []
    L.append("import GoldbachGaps.CompleteCover")
    L.append("")
    L.append("/-!")
    L.append(f"# A complete cover: a {digits}-digit even `N` with every `N - q`, `q < {Q}` prime, divisible")
    L.append(f"by a prime up to `{big}`")
    L.append("")
    L.append(f"Generated by `scripts/gen_cover.py` from {label};")
    L.append("do not edit by hand.")
    L.append(f"There are {len(rows)} primes below `{Q}`. For each of them `N - q` is divisible by one of the")
    L.append(f"{len(mods)} moduli below, so no prime below `{Q}` is a Goldbach summand of `N`. The proof is")
    L.append("divisibility only: no primality or compositeness test is evaluated. The data is not")
    L.append("trusted; Lean's kernel re-evaluates every block test.")
    L.append("-/")
    L.append("")
    L.append(f"namespace GoldbachGaps.{namespace}")
    L.append("")
    L.append("/-- The covered integer. -/")
    L.append(f"def N : ℕ :=\n  {N}")
    L.append("")
    L.append("/-- The bound: every prime below `Q` is covered. -/")
    L.append(f"def Q : ℕ := {Q}")
    L.append("")
    L.append(f"/-- `N` has {digits} digits. -/")
    L.append(f"theorem N_lt : N < 10 ^ {digits} := by decide +kernel")
    L.append("")
    L.append("theorem N_even : Even N := Nat.even_iff.mpr (by decide +kernel)")
    L.append("")
    L.append(f"/-- The {len(mods)} covering moduli (`2` covers the row `q = 2`). -/")
    L.append("def coverMods : List ℕ :=\n" + lean_list(mods))
    L.append("")
    if len(mods) > 100:
        L.append("set_option maxRecDepth 1000000 in")
        L.append(f"theorem coverMods_le : ∀ r ∈ coverMods, r ≤ {big} := by decide +kernel")
    else:
        L.append(f"theorem coverMods_le : ∀ r ∈ coverMods, r ≤ {big} := by decide")
    L.append("")
    L.append("/-- Trial divisors, enough to discard every composite `q < Q`. -/")
    L.append("def smallPrimes : List ℕ :=\n" + lean_list(small_primes))
    L.append("")
    L.append("theorem lists : desertListsCheck N Q coverMods smallPrimes = true := by")
    L.append("  decide +kernel")
    L.append("")
    blocks = []
    for k, lo in enumerate(range(0, Q, BLOCK)):
        hi = min(lo + BLOCK, Q)
        blocks.append(k)
        L.append("set_option maxRecDepth 1000000 in")
        L.append(f"theorem block{k} : CoveredIn N coverMods {lo} {hi} :=")
        L.append(f"  covered_of_desertBlockCheck_nil (g := Q) (lo := {lo}) (len := {hi - lo})")
        L.append("    lists (by decide +kernel)")
        L.append("")
    L.append(f"/-- Every prime `q < {Q}` has `N - q` divisible by a covering modulus. -/")
    L.append("theorem covered : CoveredIn N coverMods 0 Q :=")
    if len(blocks) == 1:
        L.append("  block0")
    else:
        L.append("  " + " <|\n  ".join(f"block{k}.append" for k in blocks[:-1]) + f" <|\n  block{blocks[-1]}")
    L.append("")
    L.append("/-- No prime below `Q` is a Goldbach summand of `N`. -/")
    L.append("theorem noSummand : NoSummandIn N 0 Q :=")
    L.append("  covered.noSummandIn lists le_rfl")
    L.append("")
    L.append(f"/-- **The complete cover.** `N` is even, has {digits} digits, and for every prime `q < {Q}` the")
    L.append(f"number `N - q` has a divisor `r` with `2 ≤ r ≤ {big}` (so it is composite: `r < N - q`). -/")
    L.append("theorem complete_cover :")
    L.append(f"    N < 10 ^ {digits} ∧ Even N ∧")
    L.append(f"      (∀ q < {Q}, q.Prime → ∃ r, 2 ≤ r ∧ r ≤ {big} ∧ r < N - q ∧ r ∣ N - q) ∧")
    L.append(f"      ∀ q < {Q}, ¬ IsSummand N q := by")
    L.append("  have hl := lists")
    L.append("  simp only [desertListsCheck, Bool.and_eq_true, decide_eq_true_eq, List.all_eq_true] at hl")
    L.append("  refine ⟨N_lt, N_even, fun q hq hqp => ?_, fun q hq => noSummand q (Nat.zero_le q) hq⟩")
    L.append("  obtain ⟨r, hr, hrq⟩ := covered q (Nat.zero_le q) hq hqp")
    L.append("  have h2 := hl.2 r hr")
    L.append("  have hQ : Q = " + str(Q) + " := rfl")
    L.append("  exact ⟨r, h2.1, coverMods_le r hr, by omega, hrq⟩")
    L.append("")
    # the whole progression N + t M
    M = 1
    for r in mods:
        M *= r
    tmax = (10 ** 200 - 1 - N) // M + 1 if N < 10 ** 200 else 0
    L.append("/-- The product of the moduli: the step of the covered progression. -/")
    L.append("def M : ℕ := coverMods.prod")
    L.append("")
    L.append(f"theorem M_eq : M =\n    {M} := by")
    L.append("  decide +kernel")
    L.append("")
    L.append("/-- **The covered progression.** For every `t` the number `N + t M` is even, every")
    L.append(f"`N + t M - q` with `q < {Q}` prime has a divisor `r` with `2 ≤ r ≤ {big}` and `r < N + t M - q`,")
    L.append(f"and no prime below `{Q}` is a Goldbach summand of `N + t M`. -/")
    L.append("theorem complete_cover_family (t : ℕ) :")
    L.append("    Even (N + t * M) ∧")
    L.append(f"      (∀ q < {Q}, q.Prime → ∃ r, 2 ≤ r ∧ r ≤ {big} ∧ r < N + t * M - q ∧ r ∣ N + t * M - q) ∧")
    L.append(f"      ∀ q < {Q}, ¬ IsSummand (N + t * M) q := by")
    L.append("  have hl := lists")
    L.append("  simp only [desertListsCheck, Bool.and_eq_true, decide_eq_true_eq, List.all_eq_true] at hl")
    L.append("  have hQ : Q = " + str(Q) + " := rfl")
    L.append("  have hNQ : Q ≤ N := by")
    L.append("    have := hl.1.1")
    L.append("    omega")
    L.append("  have hcov : CoveredIn (N + t * M) coverMods 0 Q := covered.add_mul hNQ t")
    L.append("  have hmods : ∀ r ∈ coverMods, 2 ≤ r ∧ r + Q < N + t * M := fun r hr => by")
    L.append("    have h2 := hl.2 r hr")
    L.append("    have : N ≤ N + t * M := Nat.le_add_right _ _")
    L.append("    exact ⟨h2.1, by omega⟩")
    L.append("  have h2M : 2 ∣ M := List.dvd_prod (List.mem_of_mem_head? rfl)" if len(mods) > 100 else
             "  have h2M : 2 ∣ M := List.dvd_prod (by decide)")
    L.append("  refine ⟨N_even.add (Even.mul_left (even_iff_two_dvd.mpr h2M) t), fun q hq hqp => ?_,")
    L.append("    fun q hq => hcov.noSummandIn_of_lt hmods q (Nat.zero_le q) hq⟩")
    L.append("  obtain ⟨r, hr, hrq⟩ := hcov q (Nat.zero_le q) hq hqp")
    L.append("  have h2 := hmods r hr")
    L.append("  exact ⟨r, h2.1, coverMods_le r hr, by omega, hrq⟩")
    L.append("")
    if tmax > 0:
        L.append(f"/-- The members of the progression below `10^200`: `t < {tmax}`. -/")
        L.append(f"theorem family_lt (t : ℕ) (ht : t < {tmax}) : N + t * M < 10 ^ 200 := by")
        L.append(f"  have h : N + {tmax - 1} * M < 10 ^ 200 := by")
        L.append("    rw [M_eq]")
        L.append("    decide +kernel")
        L.append(f"  have hle : t * M ≤ {tmax - 1} * M := Nat.mul_le_mul_right M (by omega)")
        L.append("  omega")
        L.append("")
        L.append(f"/-- ... and `t = {tmax}` is the first member that is not below `10^200`. -/")
        L.append(f"theorem family_ge : 10 ^ 200 ≤ N + {tmax} * M := by")
        L.append("  rw [M_eq]")
        L.append("  decide +kernel")
        L.append("")
    L.append(f"end GoldbachGaps.{namespace}")
    L.append("")
    with open(out, "w") as fh:
        fh.write("\n".join(L))
    print(f"{out}: N has {digits} digits, Q = {Q}, {len(rows)} primes covered by {len(mods)} moduli, "
          f"{len(blocks)} block(s)")


if __name__ == "__main__":
    main()
