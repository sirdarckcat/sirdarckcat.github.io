#!/usr/bin/env python3
"""Generate Lean certificates that given small numbers are needles at level Q: for every prime
q < Q the number N - q has a proper prime divisor, listed in the file. Divisibility only.

    python3 -I scripts/gen_needles.py Q out.lean N1 N2 ...

Each N gets `mods<N>` (the least prime factors of the N - q) and `needle_<N> : IsNeedle N Q`,
proved by the block test of `Desert.lean` with no residuals. The script refuses an N for which
some N - q is prime.
"""
import sys


def primes_below(n):
    s = bytearray([1]) * max(n, 2)
    s[0:2] = b"\x00\x00"
    for i in range(2, int(n ** 0.5) + 1):
        if s[i]:
            s[i * i::i] = bytearray(len(s[i * i::i]))
    return [i for i in range(n) if s[i]]


def least_factor(m):
    d = 2
    while d * d <= m:
        if m % d == 0:
            return d
        d += 1
    return m


def lean_list(xs, indent="  ", width=96):
    lines, cur = [], indent + "["
    for i, x in enumerate(xs):
        tok = str(x) + ("," if i + 1 < len(xs) else "]")
        if len(cur) + len(tok) + 1 > width and cur.strip() != "[":
            lines.append(cur.rstrip())
            cur = indent + " " + tok
        else:
            cur += ("" if cur.endswith("[") else " ") + tok
    lines.append(cur)
    return "\n".join(lines)


def main():
    Q, out = int(sys.argv[1]), sys.argv[2]
    Ns = [int(a) for a in sys.argv[3:]]
    rows = primes_below(Q)
    small = primes_below(int(Q ** 0.5) + 2)
    L = ["import GoldbachGaps.Needles", "", "/-!",
         f"# Needles at level `{Q}`: generated certificates", "",
         "Generated by `scripts/gen_needles.py`; do not edit by hand. For each number `N` below, every",
         f"`N - q` with `q < {Q}` prime is divisible by one of the listed primes, which is smaller than",
         "`N - q`. The data is not trusted: Lean's kernel re-evaluates the block test.", "-/", "",
         "namespace GoldbachGaps.NeedlePairs", "",
         f"/-- Trial divisors for the primes below `{Q}`. -/",
         "def smallPrimes : List ℕ :=", lean_list(small), ""]
    for N in Ns:
        mods = set()
        for q in rows:
            m = N - q
            f = least_factor(m)
            assert f < m, f"{N} - {q} is prime"
            mods.add(f)
        mods = sorted(mods)
        assert all(r + Q < N for r in mods) and Q + 2 < N
        L += [f"/-- Prime divisors of the numbers `{N} - q`, `q < {Q}` prime. -/",
              f"def mods{N} : List ℕ :=", lean_list(mods), "",
              "set_option maxRecDepth 1000000 in",
              f"theorem needle_{N} : IsNeedle {N} {Q} := by",
              f"  have hl : desertListsCheck {N} {Q} mods{N} smallPrimes = true := by decide +kernel",
              f"  have hb : desertBlockCheck {N} 0 {Q} mods{N} smallPrimes [] = true := by",
              "    decide +kernel",
              "  have hn := (covered_of_desertBlockCheck_nil hl hb).noSummandIn hl (by norm_num)",
              "  exact fun q hq => hn q (Nat.zero_le q) (by omega)", ""]
    L += ["end GoldbachGaps.NeedlePairs", ""]
    open(out, "w").write("\n".join(L))
    print(f"wrote {out}: {len(Ns)} needles at level {Q}")


if __name__ == "__main__":
    main()
