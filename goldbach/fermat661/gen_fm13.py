#!/usr/bin/env python3
"""Generates fm13_step.h: one Montgomery squaring step (times 2^b) on G groups of 8 lanes, 13 limbs of 52 bits (IFMA).

A step maps a (limbs < 2^52, value A < 4n) to Y = 2^b * A^2 * R^-1 mod n-ish (Y < 4n), R = 2^676, n < 2^664.
Phase 1: the square, the off-diagonal products a_i a_j (i < j) once, doubled, plus the diagonal.
Phase 2: Montgomery reduction, 13 rounds of m = lo52(t_i * ninv); t += m * n * 2^(52 i); carry t_i >> 52 into t_{i+1}.
Then b (a per-lane k-mask) doubles the high half, and a carry chain brings the limbs below 2^52.
Column sums stay below 2^58 (see FM13.md).
"""
import sys

L = 13
G = int(sys.argv[1]) if len(sys.argv) > 1 else 2
out = []
w = out.append
w("/* generated by gen_fm13.py %d -- do not edit */" % G)
w("#define FM13_GROUPS %d" % G)
w("#define FM13_STEP(A, N, NINV, KB) do { \\")
for g in range(G):
    w("  { __m512i *a_ = (A) + %d * 13; const __m512i *n_ = (N) + %d * 13; const __m512i ninv_ = (NINV)[%d]; const __mmask8 kb_ = (KB)[%d]; \\" % (g, g, g, g))
    w("    const __m512i zero_ = _mm512_setzero_si512(); \\")
    for i in range(L):
        w("    const __m512i a%d = a_[%d]; \\" % (i, i))
    # phase 1: off-diagonal sums e[k], k = 1 .. 24
    first = set()
    def acc_lo(k, x, y):
        v = "e%d" % k
        if k in first:
            w("    %s = _mm512_madd52lo_epu64(%s, %s, %s); \\" % (v, v, x, y))
        else:
            first.add(k)
            w("    __m512i %s = _mm512_madd52lo_epu64(zero_, %s, %s); \\" % (v, x, y))
    def acc_hi(k, x, y):
        v = "e%d" % k
        if k in first:
            w("    %s = _mm512_madd52hi_epu64(%s, %s, %s); \\" % (v, v, x, y))
        else:
            first.add(k)
            w("    __m512i %s = _mm512_madd52hi_epu64(zero_, %s, %s); \\" % (v, x, y))
    # order columns so that long chains interleave: loop over k
    for k in range(1, 25):
        # lo parts of pairs (i<j, i+j = k), hi parts of pairs with i+j = k-1
        for i in range(L):
            j = k - i
            if i < j < L:
                acc_lo(k, "a%d" % i, "a%d" % j)
        for i in range(L):
            j = k - 1 - i
            if i < j < L:
                acc_hi(k, "a%d" % i, "a%d" % j)
    # double, then diagonal: t[k] = 2 e[k] (+ diag)
    for k in range(26):
        if 1 <= k <= 24:
            w("    __m512i t%d = _mm512_add_epi64(e%d, e%d); \\" % (k, k, k))
        else:
            w("    __m512i t%d = zero_; \\" % k)
    for i in range(L):
        w("    t%d = _mm512_madd52lo_epu64(t%d, a%d, a%d); \\" % (2 * i, 2 * i, i, i))
        w("    t%d = _mm512_madd52hi_epu64(t%d, a%d, a%d); \\" % (2 * i + 1, 2 * i + 1, i, i))
    # phase 2: reduction
    for i in range(L):
        w("    { const __m512i m_ = _mm512_madd52lo_epu64(zero_, t%d, ninv_); \\" % i)
        for j in range(L):
            w("      t%d = _mm512_madd52lo_epu64(t%d, m_, n_[%d]); \\" % (i + j, i + j, j))
        for j in range(L):
            w("      t%d = _mm512_madd52hi_epu64(t%d, m_, n_[%d]); \\" % (i + j + 1, i + j + 1, j))
        w("      t%d = _mm512_add_epi64(t%d, _mm512_srli_epi64(t%d, 52)); } \\" % (i + 1, i + 1, i))
    # times 2^b, carry chain
    for k in range(L, 26):
        w("    t%d = _mm512_mask_add_epi64(t%d, kb_, t%d, t%d); \\" % (k, k, k, k))
    w("    { const __m512i mask_ = _mm512_set1_epi64(0xFFFFFFFFFFFFFULL); \\")
    w("      __m512i v_ = t%d; a_[0] = _mm512_and_si512(v_, mask_); __m512i c_ = _mm512_srli_epi64(v_, 52); \\" % L)
    for k in range(1, L):
        w("      v_ = _mm512_add_epi64(t%d, c_); a_[%d] = _mm512_and_si512(v_, mask_); c_ = _mm512_srli_epi64(v_, 52); \\" % (L + k, k))
    w("    } } \\")
w("  } while (0)")
open("fm13_step.h", "w").write("\n".join(out) + "\n")
print("fm13_step.h: %d groups, %d lines" % (G, len(out)))
