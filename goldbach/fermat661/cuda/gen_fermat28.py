#!/usr/bin/env python3
"""Generates fermat28_step.cuh: one Montgomery squaring step on 24 limbs of 28 bits, as straight-line CUDA/C++.

    python3 gen_fermat28.py [splits [outfile [redundant] [mulw]]]   # splits: independent 64-bit accumulators per column (1, 2 or 4), default 2
    from gen_fermat28 import generate; text = generate(NL=24, S=1, RED=False, MULW=False, extra_alu=0, extra_mul=0)   # for benchmarks (bench_fm28_step.py)
    # mulw: the products m_i n_j are explicit mul.wide.u32 (FM28_MADN), see FERMAT28.md: on sm_80 / 89 it removes a dead IADD3 a product

The step maps x (limbs < 2^28, value X < 4n) to 2^b * X^2 / 2^672 mod n (value < 4n), n odd, n < 2^669:
  column k = 0 .. 23   : acc += sum over i < k-i of (2 x_i) x_(k-i)  + x_(k/2)^2 (k even)  + sum over i < k of m_i n_(k-i)
                         m_k = (acc * n') mod 2^28 ; acc += m_k n_0 ; acc >>= 28
  column k = 24 .. 46  : the same with i, k-i <= 23; the limb k-24 of the result is acc mod 2^28 ; acc >>= 28
Every product is a 32x32 -> 64 bit multiply added to a 64-bit register (one IMAD.WIDE.U32); a column sum is below 2^62.
Then the carry chain of x2^b. All indices are static, so every array is in registers.
"""
import sys


def generate(NL=24, S=2, RED=False, MULW=False, extra_alu=0, extra_mul=0, W=28):
    """The text of fermat28_step*.cuh.  NL != 24 and extra_* != 0 are for timing experiments only (bench_fm28_step.py): the result is then NOT a Montgomery step of 28 x 24 bits.
    extra_alu / extra_mul: that many dummy IADD3 (two adds into a private accumulator) / dummy IMAD.WIDE (x_a x_b into a private 64-bit accumulator) per step, spread over the columns
    and folded into the output at the end (their results are never used otherwise)."""
    assert not (RED and W != 28), "redundant limbs need 3 bits of headroom in the 64-bit column sums: only the 28-bit radix has them (FERMAT28.md)"
    MK = "MASK%d" % W
    out = []
    w = out.append
    w("/* generated by gen_fermat28.py %d%s%s -- do not edit */" % (S, " redundant" if RED else "", " mulw" if MULW else ""))
    if RED:
        w("#define FM28_REDUNDANT 1   /* limbs of x are below 2^29 between steps: the kernel normalises once at the end */")
    w("#ifndef %s\n#define %s 0x%08Xu\n#endif" % (MK, MK, (1 << W) - 1))
    w("#ifndef FM28_MAD\n#ifdef FM28_ASM   /* explicit PTX: one mad.wide.u32 (IMAD.WIDE.U32) per product */\n"
      "#define FM28_MAD(acc, a, b) asm(\"mad.wide.u32 %0, %1, %2, %0;\" : \"+l\"(acc) : \"r\"(a), \"r\"(b))\n"
      "#else\n#define FM28_MAD(acc, a, b) (acc) += (u64)(a) * (b)\n#endif\n#endif")
    if MULW:
        w("#ifndef FM28_MADN     /* acc += m * n with n loop-invariant: LLVM hoists (u64) n and makes it a 64-bit multiply (mul.lo.s64), which ptxas")
        w("                         turns into IMAD.WIDE plus a dead IADD3 on sm_80 / 89; an explicit mul.wide.u32 stays a 32 x 32 -> 64 multiply */")
        w("__device__ __forceinline__ u64 fm28_mulw(u32 a, u32 b) { u64 p; asm(\"mul.wide.u32 %0, %1, %2;\" : \"=l\"(p) : \"r\"(a), \"r\"(b)); return p; }")
        w("#define FM28_MADN(acc, a, b) ((acc) += fm28_mulw(a, b))")
        w("#endif")
    w("__device__ __forceinline__ void fm28_step(u32 *x, const u32 *n, u32 np, u32 b) {")
    for i in range(NL):
        w("  const u32 x%d = x[%d], n%d = n[%d], d%d = x[%d] << 1;" % (i, i, i, i, i, i))
    for i in range(NL):
        w("  u32 m%d, y%d;" % (i, i))
    w("  u64 c = 0;")
    NDZ, NDM = 8, 4
    if extra_alu:
        w("  u32 " + ", ".join("dz%d = x%d" % (j, j % NL) for j in range(NDZ)) + ";")
    if extra_mul:
        w("  u64 " + ", ".join("dm%d = x%d" % (j, (j + 1) % NL) for j in range(NDM)) + ";")
    ncol = 2 * NL - 1
    cnt = {"alu": 0, "mul": 0}
    dummy_pairs = [("x%d" % a, "x%d" % b) for a in range(NL) for b in range(a + 1, NL)] + [("d%d" % b, "x%d" % a) for a in range(NL) for b in range(a + 1, NL)]

    def extras(col):
        """the dummy statements of column col: the totals are spread evenly"""
        lines = []
        for kind, total, nacc in (("alu", extra_alu, NDZ), ("mul", extra_mul, NDM)):
            if not total:
                continue
            want = (total * (col + 1)) // ncol - (total * col) // ncol
            for _ in range(want):
                t = cnt[kind]
                cnt[kind] += 1
                j = t % nacc
                if kind == "alu":
                    a, b = (t * 5 + 1) % NL, (t * 7 + 3) % NL
                    lines.append("    asm volatile(\"add.u32 %%0, %%0, %%1; add.u32 %%0, %%0, %%2;\" : \"+r\"(dz%d) : \"r\"(x%d), \"r\"(n%d));" % (j, a, b))
                else:
                    # distinct products that the step does not make itself (it makes d_i x_j for i < j and x_i x_i): x_a x_b and d_b x_a for a < b, in a scrambled order
                    assert extra_mul <= len(dummy_pairs), "at most %d dummy products" % len(dummy_pairs)
                    pa, pb = dummy_pairs[(t * 97) % len(dummy_pairs)]
                    lines.append("    %s(dm%d, %s, %s);" % ("FM28_MADN" if MULW else "FM28_MAD", j, pa, pb))
        return lines

    def column(k, lower):
        terms = []                                                   # (a, b) names to multiply
        if lower:
            rng = range(0, k + 1)
        else:
            rng = range(k - (NL - 1), NL)
        for i in rng:
            j = k - i
            if i < j and 0 <= j < NL and 0 <= i < NL:
                terms.append("d%d, x%d" % (i, j))
        if k % 2 == 0 and 0 <= k // 2 < NL:
            terms.append("x%d, x%d" % (k // 2, k // 2))
        red = [i for i in (range(0, k) if lower else range(k - (NL - 1), NL)) if 0 <= k - i < NL]
        for i in red:
            terms.append("m%d, n%d" % (i, k - i))
        accs = ["a%d" % s for s in range(S)]
        w("  { u64 %s;" % "; u64 ".join("%s = %s" % (a, "c" if s == 0 else "0") for s, a in enumerate(accs)))
        for t, (p) in enumerate(terms):
            a, bb = p.split(", ")
            w("    %s(%s, %s, %s);" % ("FM28_MADN" if (MULW and a.startswith("m")) else "FM28_MAD", accs[t % S], a, bb))
        if S > 1:
            w("    %s += %s;" % (accs[0], " + ".join(accs[1:])))
        if lower:
            w("    m%d = ((u32)a0 * np) & %s;" % (k, MK))
            w("    %s(a0, m%d, n0);" % ("FM28_MADN" if MULW else "FM28_MAD", k))
            w("    c = a0 >> %d; }" % W)
        else:
            w("    y%d = (u32)a0 & %s; c = a0 >> %d; }" % (k - NL, MK, W))
        for ln in extras(k):
            w(ln)

    for k in range(NL):
        column(k, True)
    for k in range(NL, 2 * NL - 1):
        column(k, False)
    w("  y%d = (u32)c;" % (NL - 1))
    if extra_alu or extra_mul:
        fold = []
        if extra_alu:
            fold.append(" ^ ".join("dz%d" % j for j in range(NDZ)))
        if extra_mul:
            fold.append(" ^ ".join("(u32)dm%d ^ (u32)(dm%d >> 32)" % (j, j) for j in range(NDM)))
        w("  y0 ^= %s;" % " ^ ".join(fold))
    if RED:
        # redundant limbs: x_i = y_i << b < 2^29, the value is 2 Y exactly; the column sums of the next step stay below 2^63 (FERMAT28.md)
        for i in range(NL):
            w("  x[%d] = y%d << b;" % (i, i))
    else:
        w("  u32 cy = 0;")
        for i in range(NL):
            w("  { const u32 v = (y%d << b) + cy; x[%d] = v & %s; cy = v >> %d; }" % (i, i, MK, W))
    w("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    S = int(sys.argv[1]) if len(sys.argv) > 1 else 2
    OUT = sys.argv[2] if len(sys.argv) > 2 else "fermat28_step.cuh"
    RED = "redundant" in sys.argv[3:]                           # limbs are left below 2^29 after the doubling: no carry chain
    MULW = "mulw" in sys.argv[3:]                              # reduction products as explicit mul.wide.u32
    text = generate(24, S, RED, MULW)
    open(OUT, "w").write(text)
    print(OUT + ": %d lines, %d accumulate lines" % (text.count("\n"), sum(1 for l in text.split("\n") if ("FM28_MAD(" in l or "FM28_MADN(" in l) and not l.startswith("#"))))
