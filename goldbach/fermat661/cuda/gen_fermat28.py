#!/usr/bin/env python3
"""Generates fermat28_step.cuh: one Montgomery squaring step on 24 limbs of 28 bits, as straight-line CUDA/C++.

    python3 gen_fermat28.py [splits [outfile]]   # splits: independent 64-bit accumulators per column (1, 2 or 4), default 2

The step maps x (limbs < 2^28, value X < 4n) to 2^b * X^2 / 2^672 mod n (value < 4n), n odd, n < 2^669:
  column k = 0 .. 23   : acc += sum over i < k-i of (2 x_i) x_(k-i)  + x_(k/2)^2 (k even)  + sum over i < k of m_i n_(k-i)
                         m_k = (acc * n') mod 2^28 ; acc += m_k n_0 ; acc >>= 28
  column k = 24 .. 46  : the same with i, k-i <= 23; the limb k-24 of the result is acc mod 2^28 ; acc >>= 28
Every product is a 32x32 -> 64 bit multiply added to a 64-bit register (one IMAD.WIDE.U32); a column sum is below 2^62.
Then the carry chain of x2^b. All indices are static, so every array is in registers.
"""
import sys

NL = 24
S = int(sys.argv[1]) if len(sys.argv) > 1 else 2
OUT = sys.argv[2] if len(sys.argv) > 2 else "fermat28_step.cuh"
out = []
w = out.append
w("/* generated by gen_fermat28.py %d -- do not edit */" % S)
w("#ifndef MASK28\n#define MASK28 0x0FFFFFFFu\n#endif")
w("#ifndef FM28_MAD\n#ifdef FM28_ASM   /* explicit PTX: one mad.wide.u32 (IMAD.WIDE.U32) per product */\n"
  "#define FM28_MAD(acc, a, b) asm(\"mad.wide.u32 %0, %1, %2, %0;\" : \"+l\"(acc) : \"r\"(a), \"r\"(b))\n"
  "#else\n#define FM28_MAD(acc, a, b) (acc) += (u64)(a) * (b)\n#endif\n#endif")
w("__device__ __forceinline__ void fm28_step(u32 *x, const u32 *n, u32 np, u32 b) {")
for i in range(NL):
    w("  const u32 x%d = x[%d], n%d = n[%d], d%d = x[%d] << 1;" % (i, i, i, i, i, i))
for i in range(NL):
    w("  u32 m%d, y%d;" % (i, i))
w("  u64 c = 0;")


def column(k, lower):
    terms = []                                                   # (a, b) names to multiply
    if lower:
        rng = range(0, k + 1)
    else:
        rng = range(k - (NL - 1), NL)
    for i in rng:
        j = k - i
        if i < j and 0 <= j < NL and 0 <= i < NL:
            terms.append("d%d, x%d" % (i, j))
    if k % 2 == 0 and 0 <= k // 2 < NL:
        terms.append("x%d, x%d" % (k // 2, k // 2))
    red = [i for i in (range(0, k) if lower else range(k - (NL - 1), NL)) if 0 <= k - i < NL]
    for i in red:
        terms.append("m%d, n%d" % (i, k - i))
    accs = ["a%d" % s for s in range(S)]
    w("  { u64 %s;" % "; u64 ".join("%s = %s" % (a, "c" if s == 0 else "0") for s, a in enumerate(accs)))
    for t, (p) in enumerate(terms):
        a, bb = p.split(", ")
        w("    FM28_MAD(%s, %s, %s);" % (accs[t % S], a, bb))
    if S > 1:
        w("    %s += %s;" % (accs[0], " + ".join(accs[1:])))
    if lower:
        w("    m%d = ((u32)a0 * np) & MASK28;" % k)
        w("    FM28_MAD(a0, m%d, n0);" % k)
        w("    c = a0 >> 28; }")
    else:
        w("    y%d = (u32)a0 & MASK28; c = a0 >> 28; }" % (k - NL))


for k in range(NL):
    column(k, True)
for k in range(NL, 2 * NL - 1):
    column(k, False)
w("  y%d = (u32)c;" % (NL - 1))
w("  u32 cy = 0;")
for i in range(NL):
    w("  { const u32 v = (y%d << b) + cy; x[%d] = v & MASK28; cy = v >> 28; }" % (i, i))
w("}")
open(OUT, "w").write("\n".join(out) + "\n")
print(OUT + ": %d lines, %d accumulate lines" % (len(out), sum(1 for l in out if "FM28_MAD(" in l and not l.startswith("#"))))
