#!/usr/bin/env python3
"""Generates fermat31_step.cuh: one Montgomery squaring step on 22 limbs of 31 bits (or 23 of 30), as straight-line CUDA/C++.

    python3 gen_fermat31.py [w [outfile]]       # w = 31 (22 limbs, default) or 30 (23 limbs)

Why: on the GPUs we run (sm_80, sm_89, sm_120) a warp-level IMAD.WIDE occupies a scheduler's multiplier pipe for about 4 cycles and the
ALU instructions run beside it on another pipe (FERMAT28.md, "Where the time goes"), so a step is as fast as its multiplications are few:
fermat28 (24 limbs of 28 bits) needs 876 of them, 22 limbs of 31 bits need 253 + 484 = 737, 23 limbs of 30 bits 276 + 529 = 805.
The price is that a product of two 31-bit limbs is below 2^62, so a 64-bit register holds only 3 of them: the products of a column are
added in groups of up to G (IMAD.WIDE with the group as the addend: one instruction a product), and the groups are added to a 96-bit
column sum (3 words, a carry chain: about one ALU instruction a product).

The step maps x (limbs < 2^w, value X < 4n) to 2^b X^2 / R mod n (value < 4n), R = 2^(w NL), n odd, 16 n < R:
  column k = 0 .. NL-1   : s = carry; s += 2 * sum_{i<j, i+j=k} x_i x_j + x_(k/2)^2 + sum_{i<k} m_i n_(k-i)
                           m_k = ((s mod 2^32) n') mod 2^w ; s += m_k n_0 ; carry = s >> w
  column k = NL .. 2NL-2 : the same with i, j <= NL-1 and no m_k; the output limb k-NL is s mod 2^w ; carry = s >> w
  the last output limb is the carry; then the carry chain of x 2^b (y_i 2^b < 2^(w+1) <= 2^32: no overflow for w <= 31).
w = 31: the cross sum is added in groups of 3 and doubled as a 96-bit number (a doubled operand times a limb would be below 2^63:
one product to a register).  w = 30: operands are doubled in advance (d_i = 2 x_i < 2^31, d_i x_j < 2^61), groups of 7 / 15.
Column sums: at most 2 * 11 + 1 + 22 products below 2^62 plus a carry below 2^38: below 2^68 < 2^96.
"""
import sys

W = int(sys.argv[1]) if len(sys.argv) > 1 else 31
OUT = sys.argv[2] if len(sys.argv) > 2 else "fermat31_step.cuh"
assert W in (30, 31)
NL = 22 if W == 31 else 23
PRED = (W == 30)                                   # pre-doubled operands for the cross terms
LIM = (1 << W) - 1
CROSS_MAX = (2 * LIM) * LIM if PRED else LIM * LIM    # largest cross product
OTHER_MAX = LIM * LIM
GC = max(1, ((1 << 64) - 1) // CROSS_MAX)          # cross products a 64-bit group can hold
GO = max(1, ((1 << 64) - 1) // OTHER_MAX)          # diagonal / reduction products
out = []
o = out.append
o("/* generated by gen_fermat31.py %d -- do not edit.  %d limbs of %d bits, groups of %d (cross) / %d (reduction) products */" % (W, NL, W, GC, GO))
o("#define FM31_W %d" % W)
o("#define FM31_NL %d" % NL)
o("#define FM31_MASK ((1u << %d) - 1u)" % W)
o("#ifndef FM31_ADD96     /* the CPU build defines a portable version */")
o("#define FM31_ADD96(s0, s1, s2, glo, ghi) asm(\"add.cc.u32 %0, %0, %3; addc.cc.u32 %1, %1, %4; addc.u32 %2, %2, 0;\" "
  ": \"+r\"(s0), \"+r\"(s1), \"+r\"(s2) : \"r\"(glo), \"r\"(ghi))")
o("#endif")
o("#ifndef FM31_MULW     /* 32 x 32 -> 64 multiply that cannot be widened to a 64-bit multiply; the CPU build defines a portable version */")
o("__device__ __forceinline__ u64 fm31_mulw(u32 a, u32 b) { u64 p; asm(\"mul.wide.u32 %0, %1, %2;\" : \"=l\"(p) : \"r\"(a), \"r\"(b)); return p; }")
o("#define FM31_MULW(a, b) fm31_mulw(a, b)")
o("#endif")
o("__device__ __forceinline__ void fm31_step(u32 *x, const u32 *n, u32 np, u32 b) {")
for i in range(NL):
    o("  const u32 x%d = x[%d], n%d = n[%d]%s;" % (i, i, i, i, (", d%d = x[%d] << 1" % (i, i)) if PRED else ""))
for i in range(NL):
    o("  u32 m%d, y%d;" % (i, i))
o("  u32 c0 = 0, c1 = 0;                        /* the carry between columns: below 2^38 */")


def groups(terms, g):
    return [terms[i:i + g] for i in range(0, len(terms), g)]


def mul(a, bb):
    """n is the same in every step, so LLVM hoists (u64) n_j out of the loop and the product with m_j becomes a 64-bit multiply
    (mul.lo.s64: ptxas then adds a dead IADD3 a product); an explicit mul.wide.u32 stays a 32 x 32 -> 64 multiply."""
    if bb.startswith("n"):
        return "FM31_MULW(%s, %s)" % (a, bb)
    return "(u64)%s * %s" % (a, bb)


def add_group(grp, tag):
    """code that adds the products of grp (list of (a, b)) to (s0, s1, s2) through one 64-bit register"""
    first = True
    for a, bb in grp:
        if first:
            o("    g = %s;" % mul(a, bb))
            first = False
        else:
            o("    g += %s;" % mul(a, bb))
    o("    FM31_ADD96(s0, s1, s2, (u32)g, (u32)(g >> 32));")


def column(k, lower):
    if lower:
        idx = range(0, k + 1)
    else:
        idx = range(k - (NL - 1), NL)
    cross = []
    for i in idx:
        j = k - i
        if i < j and 0 <= i < NL and 0 <= j < NL:
            cross.append(("d%d" % i, "x%d" % j) if PRED else ("x%d" % i, "x%d" % j))
    other = []
    if k % 2 == 0 and 0 <= k // 2 < NL:
        other.append(("x%d" % (k // 2), "x%d" % (k // 2)))
    for i in (range(0, k) if lower else range(k - (NL - 1), NL)):
        if 0 <= k - i < NL:
            other.append(("m%d" % i, "n%d" % (k - i)))
    o("  { u32 s0 = 0, s1 = 0, s2 = 0; u64 g;")
    for grp in groups(cross, GC):
        add_group(grp, "x")
    if cross and not PRED:                                                   # double the cross sum (96 bits)
        o("    s2 = __funnelshift_l(s1, s2, 1); s1 = __funnelshift_l(s0, s1, 1); s0 <<= 1;")
    o("    FM31_ADD96(s0, s1, s2, c0, c1);")
    for grp in groups(other, GO):
        add_group(grp, "o")
    if lower:
        o("    m%d = (s0 * np) & FM31_MASK;" % k)
        o("    g = FM31_MULW(m%d, n0); FM31_ADD96(s0, s1, s2, (u32)g, (u32)(g >> 32));" % k)
    else:
        o("    y%d = s0 & FM31_MASK;" % (k - NL))
    o("    c0 = __funnelshift_r(s0, s1, %d); c1 = __funnelshift_r(s1, s2, %d); }" % (W, W))


for k in range(NL):
    column(k, True)
for k in range(NL, 2 * NL - 1):
    column(k, False)
o("  y%d = c0;" % (NL - 1))
o("  u32 cy = 0;")
for i in range(NL):
    o("  { const u32 v = (y%d << b) + cy; x[%d] = v & FM31_MASK; cy = v >> %d; }" % (i, i, W))
o("}")
open(OUT, "w").write("\n".join(out) + "\n")
nprod = sum(1 for l in out if "(u64)" in l and not l.startswith("#"))
print("%s: %d limbs of %d bits, %d products, groups %d/%d" % (OUT, NL, W, nprod, GC, GO))
